"""File formats: FASTA, AGP, Hi-C contact pairs, truth tables."""
from __future__ import annotations

import gzip
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np


def _open(path, mode="rt"):
    path = str(path)
    return gzip.open(path, mode) if path.endswith(".gz") else open(path, mode)


# --------------------------------------------------------------------- FASTA
def read_fasta(path) -> dict[str, str]:
    seqs, name, buf = {}, None, []
    with _open(path) as fh:
        for line in fh:
            line = line.rstrip()
            if not line:
                continue
            if line.startswith(">"):
                if name is not None:
                    seqs[name] = "".join(buf)
                name, buf = line[1:].split()[0], []
            else:
                buf.append(line)
    if name is not None:
        seqs[name] = "".join(buf)
    return seqs


def read_lengths(path) -> dict[str, int]:
    """Contig lengths from a FASTA or a .fai / 2-column TSV."""
    p = str(path)
    if p.endswith(".fai") or p.endswith(".sizes") or p.endswith(".tsv"):
        out = {}
        with _open(p) as fh:
            for line in fh:
                f = line.split()
                out[f[0]] = int(f[1])
        return out
    return {k: len(v) for k, v in read_fasta(p).items()}


def write_fasta(seqs: dict[str, str], path, width: int = 80) -> None:
    with _open(path, "wt") as fh:
        for name, s in seqs.items():
            fh.write(f">{name}\n")
            for i in range(0, len(s), width):
                fh.write(s[i : i + width] + "\n")


_RC = str.maketrans("ACGTNacgtn", "TGCANtgcan")


def revcomp(s: str) -> str:
    return s.translate(_RC)[::-1]


# ----------------------------------------------------------------- Components
@dataclass(frozen=True)
class Component:
    """A piece of an input contig: contig[beg:end] (0-based, half-open)."""

    contig: str
    beg: int
    end: int

    @property
    def length(self) -> int:
        return self.end - self.beg

    @property
    def name(self) -> str:
        return f"{self.contig}:{self.beg + 1}-{self.end}"


@dataclass
class Scaffold:
    name: str
    parts: list[tuple[Component, int]] = field(default_factory=list)  # (component, strand +1/-1)


# ----------------------------------------------------------------------- AGP
def read_agp(path) -> list[Scaffold]:
    scafs: dict[str, Scaffold] = {}
    with _open(path) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            f = line.rstrip("\n").split("\t")
            if len(f) < 9 or f[4] in ("N", "U"):
                scafs.setdefault(f[0], Scaffold(f[0]))
                continue
            comp = Component(f[5], int(f[6]) - 1, int(f[7]))
            strand = -1 if f[8] == "-" else 1
            scafs.setdefault(f[0], Scaffold(f[0])).parts.append((comp, strand))
    return [s for s in scafs.values() if s.parts]


def write_agp(scaffolds: list[Scaffold], path, gap: int = 200) -> None:
    with open(path, "w") as fh:
        fh.write("##agp-version 2.1\n# generated by hicscaf\n")
        for s in scaffolds:
            pos, k = 0, 1
            for i, (c, strand) in enumerate(s.parts):
                if i > 0:
                    fh.write(f"{s.name}\t{pos + 1}\t{pos + gap}\t{k}\tU\t{gap}\tscaffold\tyes\tproximity_ligation\n")
                    pos += gap
                    k += 1
                fh.write(
                    f"{s.name}\t{pos + 1}\t{pos + c.length}\t{k}\tW\t{c.contig}\t{c.beg + 1}\t{c.end}\t"
                    f"{'+' if strand > 0 else '-'}\n"
                )
                pos += c.length
                k += 1


def agp_to_fasta(scaffolds: list[Scaffold], contigs: dict[str, str], gap: int = 200) -> dict[str, str]:
    out = {}
    for s in scaffolds:
        pieces = []
        for i, (c, strand) in enumerate(s.parts):
            if i > 0:
                pieces.append("N" * gap)
            seq = contigs[c.contig][c.beg : c.end]
            pieces.append(seq if strand > 0 else revcomp(seq))
        out[s.name] = "".join(pieces)
    return out


def singleton_scaffolds(lengths: dict[str, int], prefix: str = "scaffold_") -> list[Scaffold]:
    return [Scaffold(f"{prefix}{i + 1}", [(Component(n, 0, l), 1)]) for i, (n, l) in enumerate(lengths.items())]


def add_missing_components(scaffolds: list[Scaffold], lengths: dict[str, int]) -> list[Scaffold]:
    """Make sure every base of every contig is covered (AGPs sometimes drop tiny contigs)."""
    covered: dict[str, list[tuple[int, int]]] = {}
    for s in scaffolds:
        for c, _ in s.parts:
            covered.setdefault(c.contig, []).append((c.beg, c.end))
    out = list(scaffolds)
    k = len(out)
    for name, L in lengths.items():
        iv = sorted(covered.get(name, []))
        pos = 0
        for b, e in iv + [(L, L)]:
            if b > pos:
                k += 1
                out.append(Scaffold(f"scaffold_extra_{k}", [(Component(name, pos, b), 1)]))
            pos = max(pos, e)
    return out


# --------------------------------------------------------------------- Pairs
@dataclass
class Contacts:
    """Hi-C read pairs in input-contig coordinates (integer-coded contigs)."""

    names: list[str]
    c1: np.ndarray
    p1: np.ndarray
    c2: np.ndarray
    p2: np.ndarray
    w: np.ndarray | None = None   # optional counts (binned matrices from .hic / .mcool)
    resolution: int = 0           # bin size if contacts came from a binned matrix

    def __post_init__(self):
        if self.w is None:
            self.w = np.ones(len(self.c1), np.float32)

    def __len__(self):
        return len(self.c1)

    def save(self, path):
        np.savez_compressed(path, names=np.array(self.names), c1=self.c1, p1=self.p1, c2=self.c2, p2=self.p2, w=self.w,
                            resolution=self.resolution)

    @classmethod
    def load(cls, path):
        if str(path).endswith(".npz"):
            z = np.load(path)
            return cls(list(z["names"]), z["c1"], z["p1"], z["c2"], z["p2"], z["w"] if "w" in z else None,
                       int(z["resolution"]) if "resolution" in z else 0)
        return read_pairs(path)


def _raw_pos(fh) -> int:
    """Byte offset in the file on disk (compressed offset for .gz), for progress reporting."""
    raw = getattr(fh, "buffer", fh)
    raw = getattr(raw, "fileobj", raw)
    try:
        return raw.tell()
    except (OSError, ValueError):
        return 0


def read_pairs(path, names: list[str] | None = None, min_mapq: int = 0, progress=None) -> Contacts:
    """Read a 4DN .pairs file, a YaHS-style BED of read alignments, or a plain TSV `ctg1 pos1 ctg2 pos2`.

    For .pairs the standard columns are readID chr1 pos1 chr2 pos2 strand1 strand2.
    For .bed (e.g. YaHS test data LYZE01.hic.bed.gz) the two reads of a pair are consecutive lines:
    contig start end readname [mapq].
    `progress(fraction)` is called now and then with the share of the file read so far.
    """
    from array import array

    index = {n: i for i, n in enumerate(names)} if names else {}
    order = list(names) if names else []
    # compact typed arrays: a Python list of ints costs ~5x more memory on big Hi-C files
    c1, p1, c2, p2 = array("i"), array("q"), array("i"), array("q")
    size = max(1, Path(path).stat().st_size) if progress else 1
    every = 500_000

    def idx(n):
        i = index.get(n)
        if i is None:
            i = index[n] = len(order)
            order.append(n)
        return i

    with _open(path) as fh:
        if str(path).endswith((".bed", ".bed.gz")):
            prev = None
            for k, line in enumerate(fh):
                if progress and k % every == 0:
                    progress(_raw_pos(fh) / size)
                f = line.split()
                if len(f) < 4:
                    continue
                q = f[3][:-2] if f[3].endswith(("/1", "/2")) else f[3]
                mq = int(f[4]) if len(f) > 4 and f[4].isdigit() else 255
                if prev is None or prev[0] != q:
                    prev = (q, f[0], int(f[1]), mq)
                    continue
                if min(prev[3], mq) >= min_mapq:
                    c1.append(idx(prev[1])); p1.append(prev[2]); c2.append(idx(f[0])); p2.append(int(f[1]))
                prev = None
        else:
            for k, line in enumerate(fh):
                if progress and k % every == 0:
                    progress(_raw_pos(fh) / size)
                if line.startswith("#"):
                    continue
                f = line.split()
                if len(f) >= 7:  # .pairs
                    a, pa, b, pb = f[1], f[2], f[3], f[4]
                else:
                    a, pa, b, pb = f[0], f[1], f[2], f[3]
                c1.append(idx(a)); p1.append(int(pa)); c2.append(idx(b)); p2.append(int(pb))
    if progress:
        progress(1.0)
    return Contacts(order, np.frombuffer(c1, np.int32).copy(), np.frombuffer(p1, np.int64).copy(),
                    np.frombuffer(c2, np.int32).copy(), np.frombuffer(p2, np.int64).copy())


def write_pairs(ct: Contacts, path) -> None:
    with _open(path, "wt") as fh:
        fh.write("## pairs format v1.0\n#columns: readID chr1 pos1 chr2 pos2 strand1 strand2\n")
        for i in range(len(ct)):
            fh.write(f".\t{ct.names[ct.c1[i]]}\t{ct.p1[i]}\t{ct.names[ct.c2[i]]}\t{ct.p2[i]}\t+\t+\n")


# --------------------------------------------------------------------- Truth
def read_truth(path) -> dict[str, tuple[str, int, int, int]]:
    """TSV: contig  chrom  start  end  strand(+/-). Coordinates of the contig on the reference."""
    out = {}
    with open(path) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            f = line.split()
            out[f[0]] = (f[1], int(f[2]), int(f[3]), -1 if f[4] == "-" else 1)
    return out


def write_truth(truth: dict[str, tuple[str, int, int, int]], path) -> None:
    with open(path, "w") as fh:
        fh.write("#contig\tchrom\tstart\tend\tstrand\n")
        for k, (ch, s, e, st) in truth.items():
            fh.write(f"{k}\t{ch}\t{s}\t{e}\t{'+' if st > 0 else '-'}\n")


def truth_from_paf(path, min_frac: float = 0.5, min_mapq: int = 10) -> dict[str, tuple[str, int, int, int]]:
    """Place contigs on a reference from a minimap2 PAF (contigs as query)."""
    best: dict[str, tuple[int, tuple]] = {}
    with open(path) as fh:
        for line in fh:
            f = line.split("\t")
            q, qlen, qs, qe, strand, t, ts, te, nmatch, alen, mapq = (
                f[0], int(f[1]), int(f[2]), int(f[3]), f[4], f[5], int(f[7]), int(f[8]), int(f[9]), int(f[10]), int(f[11]))
            if mapq < min_mapq or (qe - qs) < min_frac * qlen:
                continue
            if q not in best or nmatch > best[q][0]:
                st = 1 if strand == "+" else -1
                # project full contig onto target coordinates
                start = ts - qs if st > 0 else ts - (qlen - qe)
                best[q] = (nmatch, (t, max(0, start), start + qlen, st))
    return {k: v[1] for k, v in best.items()}


def component_truth(comp: Component, truth):
    """Reference placement of a component.

    truth[contig] is either (chrom, start, end, strand) for a whole contig, or a list of
    (contig_beg, contig_end, chrom, start, strand) pieces (e.g. from a curated .review.assembly,
    where contigs may be split). For pieces, the piece containing the component midpoint is used.
    """
    t = truth.get(comp.contig)
    if t is None:
        return None
    if isinstance(t, list):
        mid = (comp.beg + comp.end) // 2
        for cb, ce, ch, s, st in t:
            if cb <= mid < ce:
                lo, hi = max(comp.beg, cb), min(comp.end, ce)
                if st > 0:
                    return ch, s + (lo - cb), s + (hi - cb), st
                return ch, s + (ce - hi), s + (ce - lo), st
        return None
    ch, s, e, st = t
    if st > 0:
        return ch, s + comp.beg, s + comp.end, st
    return ch, e - comp.end, e - comp.beg, st


def truth_from_scaffolds(scafs: list[Scaffold], gap: int = 0):
    """Use a trusted scaffolding (curated .review.assembly / reference AGP) as ground truth."""
    out: dict[str, list] = {}
    for s in scafs:
        pos = 0
        for c, st in s.parts:
            out.setdefault(c.contig, []).append((c.beg, c.end, s.name, pos, st))
            pos += c.length + gap
    return out
